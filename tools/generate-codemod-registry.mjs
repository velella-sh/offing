import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const directory = fileURLToPath(new URL("../src/fix/", import.meta.url));
const output = join(directory, "registry.generated.ts");

// Keep the existing tie order for patches to the same path. New codemods follow in filename order.
const establishedOrder = [
  "codemods/workflow-commands",
  "github-actions",
  "runtime-pins",
  "python",
  "go-mod",
  "java",
  "kubernetes",
  "codemods/k8s-ingress-v1",
  "dockerfile",
  "codemods/index",
  "codemods/node-buffer",
  "codemods/terraform-legacy",
  "codemods/python-imp",
  "codemods/python-renames",
  "codemods/python-utcnow",
  "codemods/node-renames",
  "codemods/dockerfile-legacy",
  "codemods/node-util-is",
];
// These fixers retain their existing contract until the coverage epic migrates them.
const existingFixers = new Set(["github-actions", "runtime-pins", "python", "kubernetes"]);

async function fixerImport(path) {
  const source = await readFile(join(directory, path + ".ts"), "utf8");
  const pattern = existingFixers.has(path)
    ? /^export const (\w+): Fixer\s*=\s*\{\s*id: "([a-z][a-z0-9-]*)"/gm
    : /^export const (\w+)\s*=\s*defineCodemod\(\{\s*id: "([a-z][a-z0-9-]*)"/gm;
  const matched = [...source.matchAll(pattern)];
  if (matched.length !== 1) throw new Error(`Expected one exported fixer with a literal id in src/fix/${path}.ts`);
  const [, name, id] = matched[0];
  return { path, name, id };
}

const modules = (await readdir(join(directory, "codemods")))
  .filter((file) => file.endsWith(".ts"))
  .sort()
  .map((file) => `codemods/${file.slice(0, -3)}`);
const paths = [...new Set([...establishedOrder, ...modules])];
const rows = await Promise.all(paths.map(fixerImport));
const names = rows.map(({ name }) => name);
if (new Set(names).size !== names.length) throw new Error("Codemod fixer exports must have unique names.");
if (new Set(rows.map(({ id }) => id)).size !== rows.length) throw new Error("Codemod ids must be unique.");

const next = `// Generated by tools/generate-codemod-registry.mjs. Do not edit by hand.
import type { Fixer } from "./types.js";
${rows.map(({ path, name }) => `import { ${name} } from "./${path}.js";`).join("\n")}

export {
${names.map((name) => `  ${name},`).join("\n")}
};

export const fixers: Fixer[] = [
${names.map((name) => `  ${name},`).join("\n")}
];
`;
const previous = await readFile(output, "utf8").catch((error) => {
  if (error.code !== "ENOENT") throw error;
  return "";
});
if (previous !== next) {
  if (process.argv.includes("--check")) {
    process.stderr.write("src/fix/registry.generated.ts is out of date. Run: npm run build\n");
    process.exitCode = 1;
  } else {
    await writeFile(output, next);
  }
}
